// 明确允许的专用库重置范围；所有数据库套件共用，新增表必须审查此清单。
import { config } from 'dotenv'
import type { RowDataPacket } from 'mysql2'
import {seedSystemRows} from '../../scripts/database/seed/system'
import {seedReferenceSystem} from '../fixtures/reference-seed'
import {migrateDatabase} from '../../scripts/lib/database-migrations.mjs'
import { validateTestDatabase } from './connection.mjs'
import { createDatabaseClient } from '../../server/db/client'
config({ path: '.env.test', quiet: true }); config({ quiet: true })

export async function setupTestDatabase({seed = true}: {seed?: boolean} = {}) {
  const target = validateTestDatabase(process.env)
  const client = createDatabaseClient(process.env.TEST_DATABASE_URL!)
  try {
    const [[identity]] = await client.pool.query<RowDataPacket[]>('SELECT DATABASE() AS name, VERSION() AS version, @@character_set_database AS charset, @@collation_database AS collation')
    if (!identity || identity.name !== target.name || !/^8\.4\./.test(identity.version) || identity.charset !== 'utf8mb4' || identity.collation !== 'utf8mb4_0900_ai_ci') throw new Error('测试库属性不匹配')
    const [tables] = await client.pool.query<RowDataPacket[]>('SELECT table_name AS name FROM information_schema.tables WHERE table_schema=DATABASE()')
    const allowed = ["career_positions","career_position_releases","news_operations","news_categories","news_articles","news_releases","admin_auth_logs","admin_dictionaries","admin_dictionary_items","admin_entity_id_counters","admin_menus","admin_operation_logs","admin_parameters","admin_permissions","admin_rate_limits","admin_role_menus","admin_role_permissions","admin_roles","admin_sessions","admin_task_commands","admin_task_runs","admin_tasks","admin_user_roles","admin_users","media_assets","media_references","website_drafts","website_navigation","website_releases","website_resources","website_sections","website_templates","website_template_revisions","website_renderers","__drizzle_migrations"]
    allowed.push('website_language_config','website_language_releases','website_image_rules','website_module_policy','website_page_seo','website_published_seo','website_site_config','website_site_config_releases','website_route_nodes','website_published_routes','customer_inquiries', 'customer_inquiry_events', 'customer_inquiry_mail', 'customer_inquiry_settings')
    if (tables.some(row => !allowed.includes(row.name))) throw new Error('发现范围外表，拒绝重置')
    await client.pool.query('DROP TABLE IF EXISTS website_language_config')
    await client.pool.query('DROP TABLE IF EXISTS website_language_releases')
    await client.pool.query('DROP TABLE IF EXISTS website_image_rules')
    await client.pool.query('DROP TABLE IF EXISTS customer_inquiry_mail')
    await client.pool.query('DROP TABLE IF EXISTS customer_inquiry_settings')
    await client.pool.query('DROP TABLE IF EXISTS customer_inquiry_events')
    await client.pool.query('DROP TABLE IF EXISTS customer_inquiries')
    const [careerConstraints]=await client.pool.query<RowDataPacket[]>("SELECT CONSTRAINT_NAME FROM information_schema.table_constraints WHERE table_schema=DATABASE() AND table_name='career_positions' AND CONSTRAINT_NAME='career_position_publication'")
    if(careerConstraints.length)await client.pool.query('ALTER TABLE career_positions DROP FOREIGN KEY career_position_publication')
    await client.pool.query('DROP TABLE IF EXISTS career_position_releases')
    await client.pool.query('DROP TABLE IF EXISTS career_positions')
    const [newsConstraints] = await client.pool.query<RowDataPacket[]>("SELECT CONSTRAINT_NAME FROM information_schema.table_constraints WHERE table_schema=DATABASE() AND table_name='news_articles' AND CONSTRAINT_NAME='news_article_publication'")
    if(newsConstraints.length)await client.pool.query('ALTER TABLE news_articles DROP FOREIGN KEY news_article_publication')
    await client.pool.query('DROP TABLE IF EXISTS news_releases')
    await client.pool.query('DROP TABLE IF EXISTS news_articles')
    await client.pool.query('DROP TABLE IF EXISTS news_categories')
    await client.pool.query('DROP TABLE IF EXISTS news_operations')
    // 固定 SQL，不禁用外键、不遍历或拼接任意库名/表名。
    const [resourceConstraints] = await client.pool.query<RowDataPacket[]>("SELECT CONSTRAINT_NAME FROM information_schema.table_constraints WHERE table_schema=DATABASE() AND table_name='website_resources' AND CONSTRAINT_NAME='website_resource_publication'")
    if(resourceConstraints.length) await client.pool.query('ALTER TABLE website_resources DROP FOREIGN KEY website_resource_publication')
    await client.pool.query('DROP TABLE IF EXISTS website_module_policy')
    await client.pool.query('DROP TABLE IF EXISTS website_site_config')
    await client.pool.query('DROP TABLE IF EXISTS website_site_config_releases')
    await client.pool.query('DROP TABLE IF EXISTS website_published_seo')
    await client.pool.query('DROP TABLE IF EXISTS website_page_seo')
    await client.pool.query('DROP TABLE IF EXISTS website_published_routes')
    await client.pool.query('DROP TABLE IF EXISTS website_route_nodes')
    await client.pool.query('DROP TABLE IF EXISTS website_sections')
    await client.pool.query('DROP TABLE IF EXISTS website_drafts')
    await client.pool.query('DROP TABLE IF EXISTS website_navigation')
    await client.pool.query('DROP TABLE IF EXISTS website_releases')
    await client.pool.query('DROP TABLE IF EXISTS website_resources')
    await client.pool.query('DROP TABLE IF EXISTS website_renderers')
    await client.pool.query('DROP TABLE IF EXISTS website_template_revisions')
    await client.pool.query('DROP TABLE IF EXISTS website_templates')
    await client.pool.query('DROP TABLE IF EXISTS media_references')
    await client.pool.query('DROP TABLE IF EXISTS media_assets')
    await client.pool.query('DROP TABLE IF EXISTS admin_task_commands')
    await client.pool.query('DROP TABLE IF EXISTS admin_task_runs')
    await client.pool.query('DROP TABLE IF EXISTS admin_tasks')
    await client.pool.query('DROP TABLE IF EXISTS admin_dictionary_items')
    await client.pool.query('DROP TABLE IF EXISTS admin_dictionaries')
    await client.pool.query('DROP TABLE IF EXISTS admin_parameters')
    await client.pool.query('DROP TABLE IF EXISTS admin_role_menus')
    await client.pool.query('DROP TABLE IF EXISTS admin_menus')
    await client.pool.query('DROP TABLE IF EXISTS admin_operation_logs')
    await client.pool.query('DROP TABLE IF EXISTS admin_user_roles')
    await client.pool.query('DROP TABLE IF EXISTS admin_role_permissions')
    await client.pool.query('DROP TABLE IF EXISTS admin_permissions')
    await client.pool.query('DROP TABLE IF EXISTS admin_roles')
    await client.pool.query('DROP TABLE IF EXISTS admin_sessions')
    await client.pool.query('DROP TABLE IF EXISTS admin_auth_logs')
    await client.pool.query('DROP TABLE IF EXISTS admin_rate_limits')
    await client.pool.query('DROP TABLE IF EXISTS admin_users')
    await client.pool.query('DROP TABLE IF EXISTS admin_entity_id_counters')
    await client.pool.query('DROP TABLE IF EXISTS __drizzle_migrations')
    await migrateDatabase(client, 'drizzle')
    if (seed) await client.database.transaction(async tx=>{await seedSystemRows(tx);await seedReferenceSystem(tx)})
    return client
  } catch (error) { await client.pool.end(); throw error }
}
export async function cleanTestDatabase(client: Awaited<ReturnType<typeof setupTestDatabase>>) {
  try {
    await client.pool.query('DELETE FROM customer_inquiry_mail')
    await client.pool.query('DELETE FROM customer_inquiry_events')
    await client.pool.query('DELETE FROM customer_inquiries')
    await client.pool.query('UPDATE career_positions SET published_release_id=NULL')
    await client.pool.query('DELETE FROM career_position_releases')
    await client.pool.query('DELETE FROM career_positions')
    await client.pool.query('UPDATE news_articles SET published_release_id=NULL')
    await client.pool.query('UPDATE news_releases SET restored_from=NULL')
    await client.pool.query('DELETE FROM news_releases')
    await client.pool.query('DELETE FROM news_articles')
    await client.pool.query('DELETE FROM news_categories')
    await client.pool.query('UPDATE news_operations SET view_count_enabled=FALSE,version=1 WHERE id=1')
    await client.pool.query('DELETE FROM media_references')
    await client.pool.query('DELETE FROM website_navigation WHERE parent_id IS NOT NULL')
    await client.pool.query('DELETE FROM website_navigation')
    await client.pool.query('DELETE FROM website_language_config')
    await client.pool.query('DELETE FROM website_language_releases')
    await client.pool.query('DELETE FROM website_site_config')
    await client.pool.query('DELETE FROM website_site_config_releases')
    await client.pool.query('DELETE FROM website_published_seo')
    await client.pool.query('DELETE FROM website_page_seo')
    await client.pool.query('UPDATE website_resources SET published_release_id=NULL')
    await client.pool.query('UPDATE website_releases SET restored_from=NULL')
    await client.pool.query('DELETE FROM website_releases')
    await client.pool.query('DELETE FROM website_sections')
    await client.pool.query('DELETE FROM website_drafts')
    await client.pool.query('DELETE FROM website_published_routes')
    await client.pool.query('UPDATE website_route_nodes SET parent_id=NULL')
    await client.pool.query('DELETE FROM website_route_nodes')
    await client.pool.query('DELETE FROM website_resources')
    await client.pool.query('DELETE FROM website_templates')
    await client.pool.query('DELETE FROM media_assets')
    await client.pool.query('DELETE FROM admin_task_commands')
    await client.pool.query('DELETE FROM admin_task_runs')
    // 固定任务及迁移配置不含账号引用，保留给同套件的后续检查。
    await client.pool.query('DELETE FROM admin_dictionary_items')
    await client.pool.query('DELETE FROM admin_dictionaries')
    await client.pool.query('DELETE FROM admin_parameters')
    await client.pool.query('DELETE FROM admin_role_menus')
    // 自引用菜单先断开父级，再按固定范围清理；不禁用外键。
    await client.pool.query('UPDATE admin_menus SET parent_id=NULL')
    await client.pool.query('DELETE FROM admin_menus')
    await client.pool.query('DELETE FROM admin_operation_logs')
    await client.pool.query('DELETE FROM admin_user_roles')
    await client.pool.query('DELETE FROM admin_role_permissions')
    await client.pool.query('DELETE FROM admin_permissions')
    await client.pool.query('DELETE FROM admin_roles')
    await client.pool.query('DELETE FROM admin_sessions')
    await client.pool.query('DELETE FROM admin_auth_logs')
    await client.pool.query('DELETE FROM admin_rate_limits')
    // 本人改密会形成自引用元数据，先解除专用测试账号的操作者引用再删除夹具。
    await client.pool.query('UPDATE admin_users SET created_by=NULL, updated_by=NULL')
    await client.pool.query('DELETE FROM admin_users WHERE is_root=0')
    await client.pool.query('DELETE FROM admin_users WHERE is_root=1')
  } finally { await client.pool.end() }
}
